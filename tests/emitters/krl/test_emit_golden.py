"""End-to-end KRL emit golden (this emitter's output, hand-reviewed).

The package-version line of the identity header is environment-dependent, so it
is normalized to `<VERSION>` before comparison; the digest lines are compared
verbatim.
"""

from __future__ import annotations

import difflib
import re
from pathlib import Path

from tesseract_robotics.emitters.krl import emit_krl
from tests.emitters.krl.spike import FRAMES, spike_composite, spike_profiles

GOLDEN = Path(__file__).parent / "golden" / "spike.src"
_VERSION_LINE = re.compile(r"(generated by tesseract_robotics\.emitters ).*")


def emit_spike_normalized() -> str:
    text = emit_krl(spike_composite(), spike_profiles(), frames=FRAMES).text
    return _VERSION_LINE.sub(r"\1<VERSION>", text)


def test_emit_krl_matches_golden() -> None:
    actual = emit_spike_normalized()
    expected = GOLDEN.read_text()
    diff = "\n".join(
        difflib.unified_diff(
            expected.splitlines(), actual.splitlines(), "golden", "emit_krl", lineterm=""
        )
    )
    assert actual == expected, f"diverged from golden:\n{diff}"
