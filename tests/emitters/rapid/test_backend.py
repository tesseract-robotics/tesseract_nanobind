"""RapidBackend: IR events to RAPID through the DSL."""

from __future__ import annotations

import pytest

from tesseract_robotics.emitters.core.backend import drive
from tesseract_robotics.emitters.core.errors import (
    ExternalAxisError,
    MissingConfigurationError,
    TcpOffsetError,
    UnboundFrameError,
)
from tesseract_robotics.emitters.core.events import (
    CartesianMove,
    JointMove,
    MoveKind,
    ProgramIR,
    SetDigital,
)
from tesseract_robotics.emitters.core.frames import FramedPose, MoveFrames
from tesseract_robotics.emitters.core.identity import EmitIdentity
from tesseract_robotics.emitters.rapid.backend import RapidBackend
from tesseract_robotics.emitters.rapid.profile import RapidProfile, rapid_frames
from tesseract_robotics.planning import Pose
from tests.emitters.programs import FRAMES, IRB2400_POSTURE, cart_move, joint_move

_PROFILES = {"P": RapidProfile(), "L": RapidProfile(), "J": RapidProfile()}
_FRAMES = rapid_frames(work_objects={"base_link": "wobj0"}, tools={"tool0": "tool0"})


def _run(events, posture=IRB2400_POSTURE) -> str:  # noqa: ANN001
    ir = ProgramIR(name="M", events=tuple(events))
    backend = RapidBackend(
        profiles=_PROFILES,
        frames=_FRAMES,
        posture=posture,
        module_name="M",
        proc_name="main",
        identity=EmitIdentity.build(ir, profiles_repr="x"),
    )
    return next(iter(drive(ir, backend).values()))


def test_timer_originated_setdigital_renders_plain_do_n() -> None:
    assert "SetDO do7, 1;" in _run([SetDigital(key=None, index=7, value=True)])


def test_named_setdigital_with_index_renders_subscript() -> None:
    assert "SetDO do_array{3}, 0;" in _run([SetDigital(key="do_array", index=3, value=False)])


def test_linear_move_emits_movel_with_exact_confdata() -> None:
    src = _run(
        [cart_move(Pose.from_xyz_quat([0.8, 0, 0.5], [0, 1, 0, 0]), seed_deg=[0, 26, 43, 0, 20, 0])]
    )
    assert "MoveL [[800.000, 0.000, 500.000]," in src
    assert ",[0, 0, 0, 0],[9E+09" in src
    assert src.strip().startswith("MODULE M") and src.strip().endswith("ENDMODULE")


def test_identity_header_is_in_module() -> None:
    src = _run([joint_move([0, 0, 0, 0, 30, 0])])
    assert src.splitlines()[2].strip().startswith("! generated by tesseract_robotics.emitters")


def test_cartesian_without_seed_raises() -> None:
    with pytest.raises(MissingConfigurationError, match="seed"):
        _run([cart_move(Pose.from_xyz(0.8, 0, 0.5))])


def test_cartesian_without_posture_raises() -> None:
    with pytest.raises(MissingConfigurationError, match="posture"):
        _run([cart_move(Pose.from_xyz(0.8, 0, 0.5), seed_deg=[0, 26, 43, 0, 20, 0])], posture=None)


def test_unbound_work_object_raises() -> None:
    frames = MoveFrames("fixture", "tool0", Pose())
    move = CartesianMove(FramedPose(Pose(), frames), MoveKind.LINEAR, "L", (0.1,) * 6)
    with pytest.raises(UnboundFrameError, match="fixture"):
        _run([move])


def test_tcp_offset_raises() -> None:
    frames = MoveFrames("base_link", "tool0", Pose.from_xyz(0, 0, 0.1))
    with pytest.raises(TcpOffsetError):
        _run([JointMove((0.1,) * 6, "J", frames)])


def test_seven_joint_values_without_layout_raise() -> None:
    with pytest.raises(ExternalAxisError):
        _run([JointMove((0.1,) * 7, "J", FRAMES)])
