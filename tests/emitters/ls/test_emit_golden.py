"""End-to-end Fanuc LS emit golden (this emitter's output, hand-reviewed).

The package-version line is normalized to `<VERSION>`; digests compare verbatim.
"""

from __future__ import annotations

import difflib
import re
from pathlib import Path

from tesseract_robotics.emitters.ls import emit_ls
from tests.emitters.ls.spike import FRAMES, posture_config, spike_composite, spike_profiles

GOLDEN = Path(__file__).parent / "golden" / "spike.ls"
_VERSION_LINE = re.compile(r"(generated by tesseract_robotics\.emitters ).*?( ;)$", re.MULTILINE)


def emit_spike_normalized() -> str:
    text = emit_ls(spike_composite(), spike_profiles(), frames=FRAMES, config=posture_config).text
    return _VERSION_LINE.sub(r"\1<VERSION>\2", text)


def test_emit_ls_matches_golden() -> None:
    actual = emit_spike_normalized()
    expected = GOLDEN.read_text()
    diff = "\n".join(
        difflib.unified_diff(
            expected.splitlines(), actual.splitlines(), "golden", "emit_ls", lineterm=""
        )
    )
    assert actual == expected, f"diverged from golden:\n{diff}"
