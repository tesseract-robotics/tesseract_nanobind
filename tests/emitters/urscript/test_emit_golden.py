"""End-to-end URScript emit golden (this emitter's output, hand-reviewed).

The package-version line is normalized to `<VERSION>`; digests compare verbatim.
"""

from __future__ import annotations

import difflib
import re
from pathlib import Path

from tesseract_robotics.emitters.urscript import emit_urscript
from tests.emitters.urscript.spike import FRAMES, spike_composite, spike_profiles

GOLDEN = Path(__file__).parent / "golden" / "spike.script"
_VERSION_LINE = re.compile(r"(generated by tesseract_robotics\.emitters ).*")


def emit_spike_normalized() -> str:
    text = emit_urscript(spike_composite(), spike_profiles(), frames=FRAMES).text
    return _VERSION_LINE.sub(r"\1<VERSION>", text)


def test_emit_urscript_matches_golden() -> None:
    actual = emit_spike_normalized()
    expected = GOLDEN.read_text()
    diff = "\n".join(
        difflib.unified_diff(
            expected.splitlines(), actual.splitlines(), "golden", "emit_urscript", lineterm=""
        )
    )
    assert actual == expected, f"diverged from golden:\n{diff}"
